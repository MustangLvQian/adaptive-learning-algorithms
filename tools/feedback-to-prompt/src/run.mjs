#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  buildDryRunReport,
  buildImprovementMessages,
  groupByTarget,
  loadFeedback,
  TARGETS,
} from './pipeline.mjs'
import { createProvider } from './providers.mjs'

const toolDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const parseArgs = (argv) => {
  const args = {
    input: join(toolDir, 'examples', 'feedback.sample.jsonl'),
    out: 'feedback-out',
    target: null,
    live: false,
    provider: 'none',
  }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--help' || arg === '-h') args.help = true
    else if (arg === '--live') args.live = true
    else if (arg === '--input') args.input = argv[++index]
    else if (arg === '--out') args.out = argv[++index]
    else if (arg === '--target') args.target = argv[++index]
    else if (arg === '--provider') args.provider = argv[++index]
    else throw new Error(`Unknown argument: ${arg}`)
  }
  return args
}

const usage = () => `Feedback -> prompt improvement pipeline

Usage:
  node tools/feedback-to-prompt/src/run.mjs [options]

Options:
  --input <file>     JSONL feedback file (default: examples/feedback.sample.jsonl)
  --out <dir>        Output directory (default: feedback-out)
  --target <name>    Only process one target (default: all)
  --live             Call the model (default: dry run, no network)
  --provider <name>  Provider for live mode: openai-compatible (default: none)
  -h, --help         Show this help

Live mode reads LLM_API_KEY, and optionally LLM_BASE_URL and LLM_MODEL, from the
environment. Output is always a draft; this tool never edits the prompts or the
algorithm source.`

const main = async () => {
  const args = parseArgs(process.argv.slice(2))
  if (args.help) {
    console.log(usage())
    return
  }
  if (args.target && !TARGETS.includes(args.target)) {
    throw new Error(`Unknown target: ${args.target}. Known: ${TARGETS.join(', ')}`)
  }

  const entries = loadFeedback(await readFile(args.input, 'utf8'))
  const groups = groupByTarget(entries)
  const outDir = resolve(args.out)
  await mkdir(outDir, { recursive: true })

  const generatedAt = new Date().toISOString()
  await writeFile(
    join(outDir, 'report.md'),
    buildDryRunReport({ entries, generatedAt }),
    'utf8',
  )

  const targets = args.target ? [args.target] : TARGETS
  const processed = []

  if (args.live) {
    const provider = createProvider({ provider: args.provider })
    for (const target of targets) {
      const targetEntries = groups.get(target) ?? []
      if (targetEntries.length === 0) continue
      const promptText = await readFile(
        join(toolDir, 'prompts', `${target}.md`),
        'utf8',
      )
      const messages = buildImprovementMessages({
        target,
        promptText,
        entries: targetEntries,
      })
      const proposal = await provider.complete(messages)
      const file = join(outDir, `proposed-${target}.md`)
      await writeFile(
        file,
        `<!-- Draft generated by ${provider.name}/${provider.model} at ${generatedAt}. ` +
          'Requires human review. Not applied automatically. -->\n\n' +
          proposal +
          '\n',
        'utf8',
      )
      processed.push(`${target} -> ${file}`)
    }
  }

  console.log(
    `Feedback: ${entries.length} entries. Report: ${join(outDir, 'report.md')}`,
  )
  if (args.live) {
    console.log(processed.length > 0 ? `Drafts:\n  ${processed.join('\n  ')}` : 'No drafts (no matching feedback).')
  } else {
    console.log('Dry run only. Re-run with --live --provider openai-compatible to draft proposals.')
  }
}

main().catch((error) => {
  console.error(`Error: ${error.message}`)
  process.exitCode = 1
})
